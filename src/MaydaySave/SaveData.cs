using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

namespace MaydaySave
{
    /// <summary>Tiny flat key/value store; one "key=value" per line, UTF-8.</summary>
    public class SaveData
    {
        public readonly Dictionary<string, string> Map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        public string Path;

        public void Set(string key, object value)
        {
            if (value == null) { Map.Remove(key); return; }
            string s;
            if (value is bool b) s = b ? "1" : "0";
            else if (value is float f) s = f.ToString("R", CultureInfo.InvariantCulture);
            else if (value is double d) s = d.ToString("R", CultureInfo.InvariantCulture);
            else s = Convert.ToString(value, CultureInfo.InvariantCulture);
            Map[key] = s;
        }

        public string Str(string key, string def = "") => Map.TryGetValue(key, out var v) ? v : def;
        public int Int(string key, int def = 0) => Map.TryGetValue(key, out var v) && int.TryParse(v, NumberStyles.Integer, CultureInfo.InvariantCulture, out var r) ? r : def;
        public float Float(string key, float def = 0f) => Map.TryGetValue(key, out var v) && float.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out var r) ? r : def;
        public double Double(string key, double def = 0d) => Map.TryGetValue(key, out var v) && double.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out var r) ? r : def;
        public long Long(string key, long def = 0L) => Map.TryGetValue(key, out var v) && long.TryParse(v, NumberStyles.Integer, CultureInfo.InvariantCulture, out var r) ? r : def;
        public bool Bool(string key, bool def = false) => Map.TryGetValue(key, out var v) && (v == "1" || v.Equals("true", StringComparison.OrdinalIgnoreCase));
        public bool Has(string key) => Map.ContainsKey(key);

        public void SaveTo(string path)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Mayday Airways save - generated by MaydaySave mod");
            foreach (var kv in Map) sb.Append(kv.Key).Append('=').Append(Escape(kv.Value)).AppendLine();
            var tmp = path + ".tmp";
            File.WriteAllText(tmp, sb.ToString(), Encoding.UTF8);
            if (File.Exists(path)) File.Delete(path);
            File.Move(tmp, path);
            Path = path;
        }

        public static SaveData LoadFrom(string path)
        {
            var d = new SaveData { Path = path };
            foreach (var raw in File.ReadAllLines(path, Encoding.UTF8))
            {
                var line = raw.TrimEnd();
                if (line.Length == 0 || line[0] == '#') continue;
                int eq = line.IndexOf('=');
                if (eq <= 0) continue;
                d.Map[line.Substring(0, eq)] = Unescape(line.Substring(eq + 1));
            }
            return d;
        }

        private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\n", "\\n").Replace("\r", "");

        private static string Unescape(string s)
        {
            if (s.IndexOf('\\') < 0) return s;
            var sb = new StringBuilder(s.Length);
            for (int i = 0; i < s.Length; i++)
            {
                if (s[i] == '\\' && i + 1 < s.Length)
                {
                    char n = s[++i];
                    sb.Append(n == 'n' ? '\n' : n);
                }
                else sb.Append(s[i]);
            }
            return sb.ToString();
        }
    }
}
